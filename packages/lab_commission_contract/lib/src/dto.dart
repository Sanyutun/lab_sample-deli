/// Wire DTOs for the companion API. JSON keys are camelCase.
///
/// These mirror the office app's authoritative models 1:1 so no second,
/// competing representation of commissions/rewards is introduced.
library;

/// One delivery-man identity as returned to the companion app. Never carries
/// commission rules or other people's data.
class DeliveryManProfileDto {
  const DeliveryManProfileDto({
    required this.id,
    required this.name,
    required this.phone,
  });

  final String id;
  final String name;
  final String phone;

  Map<String, dynamic> toJson() => {'id': id, 'name': name, 'phone': phone};

  factory DeliveryManProfileDto.fromJson(Map<String, dynamic> json) =>
      DeliveryManProfileDto(
        id: json['id'] as String,
        name: json['name'] as String,
        phone: (json['phone'] as String?) ?? '',
      );
}

