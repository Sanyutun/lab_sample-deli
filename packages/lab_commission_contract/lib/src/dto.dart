/// Office-wide GPS tracking policy the delivery-man app must follow. The phone
/// only reads it; the office is the single source of truth.
///
/// [intervalMinutes] is how often a fix is captured while signed in;
/// [retentionMinutes] is how long a *sent* fix stays on the phone's own list.
/// Neither changes how long the office keeps raw fixes.
class GpsPolicyDto {
  const GpsPolicyDto({
    required this.intervalMinutes,
    required this.retentionMinutes,
  });

  /// The values used when the office has never set a policy. Three days of
  /// fixes is the office's default so a location history is reviewable.
  static const GpsPolicyDto standard = GpsPolicyDto(
    intervalMinutes: 2,
    retentionMinutes: threeDaysMinutes,
  );

  /// Three days, the longest retention offered.
  static const int threeDaysMinutes = 4320;

  /// Allowed values, shared so the office dropdown and the phone cannot drift.
  static const List<int> intervalOptions = [1, 2, 5, 10, 15, 30];
  static const List<int> retentionOptions = [
    5,
    10,
    20,
    30,
    60,
    threeDaysMinutes,
  ];

  final int intervalMinutes;
  final int retentionMinutes;

  Duration get interval => Duration(minutes: intervalMinutes);
  Duration get retention => Duration(minutes: retentionMinutes);

  Map<String, dynamic> toJson() => {
    'intervalMinutes': intervalMinutes,
    'retentionMinutes': retentionMinutes,
  };

  factory GpsPolicyDto.fromJson(Map<String, dynamic> json) => GpsPolicyDto(
    intervalMinutes:
        (json['intervalMinutes'] as num?)?.toInt() ?? standard.intervalMinutes,
    retentionMinutes:
        (json['retentionMinutes'] as num?)?.toInt() ??
        standard.retentionMinutes,
  );
}

/// A captured GPS fix. Always tied server-side to the authenticated delivery man.
class GeoPointDto {
  const GeoPointDto({
    required this.id,
    required this.latitude,
    required this.longitude,
    required this.capturedAt,
    this.accuracyM,
    this.barcode,
    this.clientId,
  });

  final String id;
  final double latitude;
  final double longitude;

  /// Accuracy radius in metres, when the device reported one.
  final double? accuracyM;
  final int capturedAt;

  /// Optional receipt this fix belongs to.
  final String? barcode;

  /// Id the phone assigned when it queued the fix. Lets a phone retry a send
  /// that it never saw the reply to without creating a second copy.
  final String? clientId;

  Map<String, dynamic> toJson() => {
    'id': id,
    'latitude': latitude,
    'longitude': longitude,
    if (accuracyM != null) 'accuracyM': accuracyM,
    'capturedAt': capturedAt,
    if (barcode != null) 'barcode': barcode,
    if (clientId != null) 'clientId': clientId,
  };

  factory GeoPointDto.fromJson(Map<String, dynamic> json) => GeoPointDto(
    id: json['id'] as String,
    latitude: (json['latitude'] as num).toDouble(),
    longitude: (json['longitude'] as num).toDouble(),
    capturedAt: (json['capturedAt'] as num).toInt(),
    accuracyM: json['accuracyM'] == null
        ? null
        : (json['accuracyM'] as num).toDouble(),
    barcode: json['barcode'] as String?,
    clientId: json['clientId'] as String?,
  );
}

