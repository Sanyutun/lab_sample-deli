/// One delivery (commission) record, read-only.
class CommissionDto {
  const CommissionDto({
    required this.id,
    required this.barcode,
    required this.commission,
    required this.dateTime,
    required this.paymentStatus,
    required this.reconciliationStatus,
    this.paidAt,
    this.payments = const [],
  });

  final String id;
  final String barcode;
  final int commission;
  final int dateTime;

  /// 'paid' | 'unpaid'
  final String paymentStatus;

  /// 'match' | 'mismatch' | 'notFound' | 'duplicate' | 'unclaimed' | 'unknown'
  final String reconciliationStatus;
  final int? paidAt;
  final List<PaymentEntryDto> payments;

  bool get isPaid => paymentStatus == 'paid';

  Map<String, dynamic> toJson() => {
    'id': id,
    'barcode': barcode,
    'commission': commission,
    'dateTime': dateTime,
    'paymentStatus': paymentStatus,
    'reconciliationStatus': reconciliationStatus,
    if (paidAt != null) 'paidAt': paidAt,
    'payments': [for (final p in payments) p.toJson()],
  };

  factory CommissionDto.fromJson(Map<String, dynamic> json) => CommissionDto(
    id: json['id'] as String,
    barcode: json['barcode'] as String,
    commission: (json['commission'] as num).toInt(),
    dateTime: (json['dateTime'] as num).toInt(),
    paymentStatus: json['paymentStatus'] as String,
    reconciliationStatus:
        (json['reconciliationStatus'] as String?) ?? 'unknown',
    paidAt: json['paidAt'] == null ? null : (json['paidAt'] as num).toInt(),
    payments: [
      for (final p in (json['payments'] as List? ?? const []))
        PaymentEntryDto.fromJson(p as Map<String, dynamic>),
    ],
  );
}

