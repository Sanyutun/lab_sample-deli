/// One position on the delivery board. Slots only *represent* positions; the
/// underlying commission is the single source of truth and is never created
/// from the board. Mirrors the office app's `DeliverySlot`.
class BoardSlotDto {
  const BoardSlotDto({
    required this.number,
    required this.state,
    this.commission = 0,
    this.paid = false,
    this.milestoneAmount,
    this.barcode,
    this.recordedAt,
    this.reconciliationStatus,
  });

  /// Stable sequential display number (1-based) for the delivery man.
  final int number;

  /// 'empty' | 'successful' | 'pending' | 'reversed'
  final String state;

  /// Commission of the underlying delivery; 0 when the slot is empty.
  final int commission;
  final bool paid;

  /// Amount of the milestone reward earned exactly at this position, if any.
  final int? milestoneAmount;

  final String? barcode;
  final int? recordedAt;

  /// 'match' | 'mismatch' | 'notFound' | 'duplicateStaff'
  /// | 'duplicateOfficial' | 'unclaimed', when reconciled.
  final String? reconciliationStatus;

  bool get isEmpty => state == 'empty';

  Map<String, dynamic> toJson() => {
    'number': number,
    'state': state,
    'commission': commission,
    'paid': paid,
    if (milestoneAmount != null) 'milestoneAmount': milestoneAmount,
    if (barcode != null) 'barcode': barcode,
    if (recordedAt != null) 'recordedAt': recordedAt,
    if (reconciliationStatus != null)
      'reconciliationStatus': reconciliationStatus,
  };

  factory BoardSlotDto.fromJson(Map<String, dynamic> json) => BoardSlotDto(
    number: (json['number'] as num).toInt(),
    state: json['state'] as String,
    commission: (json['commission'] as num?)?.toInt() ?? 0,
    paid: (json['paid'] as bool?) ?? false,
    milestoneAmount: (json['milestoneAmount'] as num?)?.toInt(),
    barcode: json['barcode'] as String?,
    recordedAt: json['recordedAt'] == null
        ? null
        : (json['recordedAt'] as num).toInt(),
    reconciliationStatus: json['reconciliationStatus'] as String?,
  );
}

/// A group of [BoardSlotDto]s (10 per group, laid out 5 x 2).
class BoardGroupDto {
  const BoardGroupDto({
    required this.groupNumber,
    required this.startNumber,
    required this.endNumber,
    required this.slots,
    required this.successfulCount,
    required this.commissionTotal,
    required this.milestoneAmounts,
  });

  final int groupNumber;
  final int startNumber;
  final int endNumber;
  final List<BoardSlotDto> slots;

  /// Successful deliveries physically located in this group.
  final int successfulCount;

  /// Commission earned by the successful deliveries of this group.
  final int commissionTotal;

  /// Amounts of the milestone rewards earned at positions inside this group.
  final List<int> milestoneAmounts;

  Map<String, dynamic> toJson() => {
    'groupNumber': groupNumber,
    'startNumber': startNumber,
    'endNumber': endNumber,
    'successfulCount': successfulCount,
    'commissionTotal': commissionTotal,
    'milestoneAmounts': milestoneAmounts,
    'slots': [for (final s in slots) s.toJson()],
  };

  factory BoardGroupDto.fromJson(Map<String, dynamic> json) => BoardGroupDto(
    groupNumber: (json['groupNumber'] as num).toInt(),
    startNumber: (json['startNumber'] as num).toInt(),
    endNumber: (json['endNumber'] as num).toInt(),
    successfulCount: (json['successfulCount'] as num?)?.toInt() ?? 0,
    commissionTotal: (json['commissionTotal'] as num?)?.toInt() ?? 0,
    milestoneAmounts: [
      for (final a in (json['milestoneAmounts'] as List? ?? const []))
        (a as num).toInt(),
    ],
    slots: [
      for (final s in (json['slots'] as List? ?? const []))
        BoardSlotDto.fromJson(s as Map<String, dynamic>),
    ],
  );
}

